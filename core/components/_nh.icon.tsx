export type TLucideIcon = keyof typeof Icons;

interface ILucideIcon {
   icon: TLucideIcon;
   size?: number;
   className?: string;
}

export const NHIcon = ({ icon, ...props }: ILucideIcon) => {
   const IconRender = Icons[icon];

   if (!IconRender) {
      console.warn(`Icon "${icon}" not found`);
      return null;
   }

   return <IconRender {...props} />;
};